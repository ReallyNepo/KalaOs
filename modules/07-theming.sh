    background-color: @surface;
    text-color: @accent-red;
}

element-icon {
    size: 24px;
    padding: 0 8px 0 0;
}
ROFI_THEME_EOF

# ─── GTK theme (adw-gtk3 custom) ──────────────────────────────
mkdir -p "$HOME/.config/gtk-3.0" "$HOME/.config/gtk-4.0"
cat > "$HOME/.config/gtk-3.0/gtk.css" <<GTK_CSS_EOF
/* KalaOS GTK3 Theme */
@define-color bg_color $BG;
@define-color fg_color $FG;
@define-color base_color $SURFACE;
