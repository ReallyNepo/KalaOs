# ─── Generador de temas desde wallpaper ────────────────────────
run_cmd "mkdir -p ${SCRIPT_DIR:-$HOME/kalaos}/modules" "Modules dir"
cat > ${KALAOS_REPO:-$HOME/kalaos}/modules/generate-theme.sh <<'GEN_THEME_EOF'
#!/usr/bin/env bash
# Genera temas para todos los componentes desde un wallpaper
# Uso: generate-theme.sh /ruta/a/wallpaper.jpg

set -euo pipefail

WALLPAPER="${1:-}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KALAOS_DIR="$(dirname "$SCRIPT_DIR")"
THEME_DIR="$HOME/.config/kalaos/theme"
CACHE_DIR="$HOME/.cache/kalaos"

mkdir -p "$THEME_DIR" "$CACHE_DIR"

if [[ -z "$WALLPAPER" || ! -f "$WALLPAPER" ]]; then
    echo "Usando paleta base KalaOS (sin wallpaper)"
    cp "$KALAOS_DIR/assets/theme/kalaos-palette.json" "$THEME_DIR/current.json"
else
    echo "Generando paleta desde: $WALLPAPER"
    # matugen genera JSON + aplica a GTK/QT
    matugen image "$WALLPAPER" --type json --out "$THEME_DIR/current.json" 2>/dev/null || \
    wallust palette "$WALLPAPER" --backend wal --output "$THEME_DIR/current.json"
fi

# Cargar paleta
PALETTE_FILE="$THEME_DIR/current.json"
BG=$(jq -r '.background' "$PALETTE_FILE")
FG=$(jq -r '.foreground' "$PALETTE_FILE")
ACCENT_PURPLE=$(jq -r '.accent_purple // .color2' "$PALETTE_FILE")
ACCENT_RED=$(jq -r '.accent_red // .color1' "$PALETTE_FILE")
SURFACE=$(jq -r '.surface // .color0' "$PALETTE_FILE")
BORDER=$(jq -r '.border // .color8' "$PALETTE_FILE")
MUTED=$(jq -r '.muted // .color8' "$PALETTE_FILE")

# ─── Waybar colors ────────────────────────────────────────────
cat > "$HOME/.config/waybar/colors-waybar.css" <<WAYBAR_CSS_EOF
/* Auto-generated by KalaOS theming */
:root {
    --background: $BG;
    --foreground: $FG;
    --accent-purple: $ACCENT_PURPLE;
    --accent-red: $ACCENT_RED;
    --surface: $SURFACE;
    --surface-hover: ${SURFACE}ee;
    --border: $BORDER;
    --foreground-muted: $MUTED;
}
WAYBAR_CSS_EOF

# ─── Hyprland colors ──────────────────────────────────────────
cat > "$HOME/.config/hypr/colors-hyprland.conf" <<HYPR_CSS_EOF
# Auto-generated by KalaOS theming
\$background = $BG
\$foreground = $FG
\$accent_purple = $ACCENT_PURPLE
\$accent_red = $ACCENT_RED
\$surface = $SURFACE
\$border = $BORDER
\$muted = $MUTED

# Window rules
general {
    col.active_border = rgba(${ACCENT_PURPLE#\#}ee) rgba(${ACCENT_RED#\#}ee) 45deg
    col.inactive_border = rgba(${BORDER#\#}aa)
    col.group_border = rgba(${ACCENT_PURPLE#\#}ee)
    col.group_border_active = rgba(${ACCENT_RED#\#}ee)
    col.urgent_border = rgba(${ACCENT_RED#\#}ee)
}

# Decorations
decoration:blur {
    enabled = true
    size = 8
    passes = 3
    new_optimizations = true
    xray = true
    ignore_opacity = false
}

decoration:rounding {
    rounding = 8
}
HYPR_CSS_EOF

# ─── Ghostty theme ────────────────────────────────────────────
cat > "$HOME/.config/ghostty/themes/kalaos-purple-red.conf" <<GHOSTTY_THEME_EOF
# Auto-generated by KalaOS theming
background = $BG
foreground = $FG
cursor = $ACCENT_RED
selection = ${ACCENT_PURPLE}60

# ANSI colors
palette = 0=$BG
palette = 1=$ACCENT_RED
palette = 2=$ACCENT_PURPLE
palette = 3=$(jq -r '.color3' "$PALETTE_FILE")
palette = 4=$(jq -r '.color4' "$PALETTE_FILE")
palette = 5=$(jq -r '.color5' "$PALETTE_FILE")
palette = 6=$(jq -r '.color6' "$PALETTE_FILE")
palette = 7=$FG
palette = 8=$MUTED
palette = 9=$(jq -r '.color9' "$PALETTE_FILE")
palette = 10=$(jq -r '.color10' "$PALETTE_FILE")
palette = 11=$(jq -r '.color11' "$PALETTE_FILE")
palette = 12=$(jq -r '.color12' "$PALETTE_FILE")
palette = 13=$(jq -r '.color13' "$PALETTE_FILE")
palette = 14=$(jq -r '.color14' "$PALETTE_FILE")
palette = 15=$(jq -r '.color15' "$PALETTE_FILE")

# Syntax highlighting (IDE-like)
# Estos son overrides para tree-sitter / shell highlighting
# Fish shell highlighting
shell-fish-command = $ACCENT_PURPLE
shell-fish-builtin = $ACCENT_RED
shell-fish-function = $ACCENT_PURPLE
shell-fish-variable = $FG
shell-fish-string = $(jq -r '.color2' "$PALETTE_FILE")
shell-fish-number = $(jq -r '.color3' "$PALETTE_FILE")
shell-fish-comment = $MUTED
shell-fish-operator = $ACCENT_RED
shell-fish-keyword = $ACCENT_PURPLE
GHOSTTY_THEME_EOF

# ─── Rofi theme ───────────────────────────────────────────────
cat > "$HOME/.config/rofi/kalaos-theme.rasi" <<ROFI_THEME_EOF
