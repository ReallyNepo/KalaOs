@define-color accent_bg_color $ACCENT_PURPLE;
@define-color accent_fg_color $BG;
@define-color accent_color $ACCENT_RED;
GTK4_CSS_EOF

# ─── Starship palette ─────────────────────────────────────────
cat > "$HOME/.config/starship/palette.toml" <<STARSHIP_PALETTE_EOF
# Auto-generated by KalaOS theming
palette = """
$bg = "$BG"
$fg = "$FG"
$purple = "$ACCENT_PURPLE"
$red = "$ACCENT_RED"
$muted = "$MUTED"
$surface = "$SURFACE"
"""
STARSHIP_PALETTE_EOF

# ─── Setea wallpaper con swww ─────────────────────────────────
if [[ -n "$WALLPAPER" && -f "$WALLPAPER" ]]; then
    swww img "$WALLPAPER" --transition-type grow --transition-duration 1 --transition-fps 60 2>/dev/null || true
fi

echo "Tema aplicado: $ACCENT_PURPLE / $ACCENT_RED sobre $BG"
GEN_THEME_EOF

chmod +x ${KALAOS_REPO:-$HOME/kalaos}/modules/generate-theme.sh

# ─── Script kala wallpaper (integración CLI) ───────────────────
run_cmd "mkdir -p ${SCRIPT_DIR:-$HOME/kalaos}/dotfiles/kala" "Kala dotfiles dir"
cat > ${KALAOS_REPO:-$HOME/kalaos}/dotfiles/kala/kala-wallpaper <<'KALA_WALL_EOF'
#!/usr/bin/env fish
# kala wallpaper - Setea wallpaper y regenera tema completo

function kala_wallpaper --description 'Set wallpaper and regenerate system theme'
    set -l wallpaper $argv[1]

    if test -z "$wallpaper"
        echo "Uso: kala wallpaper <ruta-a-imagen>"
        return 1
    end

    if not test -f "$wallpaper"
        echo "Archivo no encontrado: $wallpaper"
        return 1
    end

    # Ejecutar generador de temas
    ${KALAOS_REPO:-$HOME/kalaos}/modules/generate-theme.sh "$wallpaper"

    # Recargar waybar
    pkill -USR2 waybar 2>/dev/null || true

    # Recargar hyprland
    hyprctl reload 2>/dev/null || true

    # Notificar
    notify-send "KalaOS Theme" "Wallpaper y tema actualizados" -i preferences-desktop-wallpaper
end
KALA_WALL_EOF

chmod +x ${KALAOS_REPO:-$HOME/kalaos}/dotfiles/kala/kala-wallpaper

# ─── Aplicar tema base inicial ────────────────────────────────
${KALAOS_REPO:-$HOME/kalaos}/modules/generate-theme.sh

log_ok "Theming module completed"