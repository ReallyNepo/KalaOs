@define-color selected_bg_color $ACCENT_PURPLE;
@define-color selected_fg_color $BG;
@define-color theme_bg_color $BG;
@define-color theme_fg_color $FG;
@define-color theme_base_color $SURFACE;
@define-color theme_text_color $FG;
@define-color theme_selected_bg_color $ACCENT_PURPLE;
@define-color theme_selected_fg_color $BG;
@define-color theme_unfocused_bg_color $SURFACE;
@define-color theme_unfocused_fg_color $MUTED;
GTK_CSS_EOF

cat > "$HOME/.config/gtk-4.0/gtk.css" <<GTK4_CSS_EOF
/* KalaOS GTK4 Theme */
@define-color bg_color $BG;
@define-color fg_color $FG;
