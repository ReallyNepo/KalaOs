# Module: 07-theming - Sistema de colores morado/rojo + wallpaper→palette (matugen/wallust)

log_step "Installing theming system (matugen + wallpaper palette generation)"

THEMING_PKGS=(
    matugen
    wallust
    swww                    # Wallpaper daemon para hyprland
    swaybg                  # Fallback wallpaper
    gnome-themes-extra      # GTK themes base
    adw-gtk-theme           # GTK4 themes
    kvantum                 # QT theming (Qt5 + Qt6)
    nwg-look                # GTK3/4 theme editor (GUI)
)

pacman_install "${THEMING_PKGS[@]}"
# aether-gtk-theme not in AUR; adw-gtk-theme (pacman) provides GTK theming
# aur_install aether-gtk-theme

# ─── Colores base KalaOS (morado/rojo) ─────────────────────────
# Paleta base morado/rojo para cuando no hay wallpaper
run_cmd "mkdir -p ${SCRIPT_DIR:-$HOME/kalaos}/assets/theme" "Assets theme dir"
cat > ${KALAOS_REPO:-$HOME/kalaos}/assets/theme/kalaos-palette.json <<'PALETTE_EOF'
